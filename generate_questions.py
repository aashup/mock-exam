# Generate all questions
all_questions = []
question_counter = 1

for topic_key, topic_data in topics.items():
    questions_per_topic = topic_data["count"]
    questions_per_subtopic = questions_per_topic // len(topic_data["subtopics"])
    remainder = questions_per_topic % len(topic_data["subtopics"])

    for sub_idx, subtopic in enumerate(topic_data["subtopics"]):
        # Distribute questions
        qcount = questions_per_subtopic + (1 if sub_idx < remainder else 0)

        for q_idx in range(qcount):
            template = topic_data["templates"][q_idx % len(topic_data["templates"])]
            question_pattern, options_templates, correct_idx = template

            # Build question text
            if "के बारे में" in question_pattern:
                question_text = subtopic + " " + question_pattern
            elif "निम्नलिखित में से कौन से से संबंधित नहीं है?" in question_pattern:
                question_text = subtopic + " " + question_pattern
            elif question_pattern.startswith("के"):
                question_text = subtopic + " " + question_pattern
            else:
                question_text = subtopic + " " + question_pattern

            # Build options
            if question_pattern == "के बारे में निम्नलिखित में से कौन सा कथन सही है?":
                opts = options_templates
            else:
                opts = options_templates

            options_list = [
                {"text": opt, "is_correct": (i == correct_idx)}
                for i, opt in enumerate(opts)
            ]

            # Generate explanation
            explanation = f"{subtopic} से संबंधित यह प्रश्न परीक्षा के लिए महत्वपूर्ण है। सही उत्तर है: {opts[correct_idx]}। यह {subtopic} के मुख्य पहलुओं को समझने में मदद करता है।"

            question_obj = {
                "question": question_text,
                "options": options_list,
                "explanation": explanation
            }

            all_questions.append(question_obj)

print(f"[+] Successfully generated {len(all_questions)} MCQ questions")

topics_list = list(questions_db.keys())
questions_per_topic = 500 // len(topics_list)
extra_questions = 500 % len(topics_list)

for topic_idx, topic_name in enumerate(topics_list):
    count = questions_per_topic + (1 if topic_idx < extra_questions else 0)
    topic_questions = questions_db[topic_name]

    for i in range(count):
        # Get a unique question from the topic
        q_idx = i % len(topic_questions)
        question_text, options, correct_idx = topic_questions[q_idx]

        # Create options array
        options_array = [
            {"text": opt, "is_correct": (j == correct_idx)}
            for j, opt in enumerate(options)
        ]

        # Create explanation
        correct_answer = options[correct_idx]
        explanation = f"यह प्रश्न {topic_name} से संबंधित है। सही उत्तर है: {correct_answer}। यह उत्तर सिलेबस के अनुसार सही है और परीक्षा की दृष्टि से महत्वपूर्ण है।"

        question_obj = {
            "question": question_text,
            "options": options_array,
            "explanation": explanation
        }

        all_questions.append(question_obj)
        question_count += 1

